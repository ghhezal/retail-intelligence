
BEGIN;

-- Branches
CREATE TABLE branches (
    branch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    city VARCHAR(100) NOT NULL,
    address TEXT NOT NULL,
    phone VARCHAR(30),

    CHECK (TRIM(name) <> '')
);

-- Categories
CREATE TABLE categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,

    CHECK (TRIM(name) <> '')
);

-- Brands
CREATE TABLE brands (
    brand_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,

    CHECK (TRIM(name) <> '')
);

-- Suppliers
CREATE TABLE suppliers (
    supplier_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255),
    phone VARCHAR(30),
    address TEXT,

    CHECK (TRIM(name) <> '')
);

-- Products
CREATE TABLE products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL,
    brand_id BIGINT NOT NULL,

    sku VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    description TEXT,

    cost_price NUMERIC(12, 2) NOT NULL,
    selling_price NUMERIC(12, 2) NOT NULL,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_products_category
        FOREIGN KEY (category_id)
        REFERENCES categories(category_id),

    CONSTRAINT fk_products_brand
        FOREIGN KEY (brand_id)
        REFERENCES brands(brand_id),

    CONSTRAINT chk_product_cost
        CHECK (cost_price >= 0),

    CONSTRAINT chk_product_price
        CHECK (selling_price >= 0),

    CONSTRAINT chk_product_name
        CHECK (TRIM(name) <> ''),

    CONSTRAINT chk_product_sku
        CHECK (TRIM(sku) <> '')
);

-- Links suppliers to the products they offer
CREATE TABLE supplier_products (
    supplier_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,

    supplier_sku VARCHAR(100),
    supplier_price NUMERIC(12, 2) NOT NULL,

    PRIMARY KEY (supplier_id, product_id),

    FOREIGN KEY (supplier_id)
        REFERENCES suppliers(supplier_id),

    FOREIGN KEY (product_id)
        REFERENCES products(product_id),

    CONSTRAINT uq_supplier_sku
        UNIQUE (supplier_id, supplier_sku),

    CONSTRAINT chk_supplier_price
        CHECK (supplier_price >= 0)
);

-- Stock available at each branch
CREATE TABLE inventory (
    branch_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,

    quantity INTEGER NOT NULL DEFAULT 0,
    reorder_level INTEGER NOT NULL DEFAULT 5,

    PRIMARY KEY (branch_id, product_id),

    FOREIGN KEY (branch_id)
        REFERENCES branches(branch_id),

    FOREIGN KEY (product_id)
        REFERENCES products(product_id),

    CONSTRAINT chk_inventory_quantity
        CHECK (quantity >= 0),

    CONSTRAINT chk_reorder_level
        CHECK (reorder_level >= 0)
);

-- Customers
CREATE TABLE customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(255) UNIQUE,
    phone VARCHAR(30),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CHECK (TRIM(full_name) <> '')
);

-- Sales
CREATE TABLE sales (
    sale_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    branch_id BIGINT NOT NULL,
    customer_id BIGINT,

    sold_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    payment_method VARCHAR(30) NOT NULL,

    FOREIGN KEY (branch_id)
        REFERENCES branches(branch_id),

    FOREIGN KEY (customer_id)
        REFERENCES customers(customer_id)
        ON DELETE SET NULL,

    CONSTRAINT chk_payment_method
        CHECK (
            payment_method IN (
                'cash',
                'card',
                'bank_transfer'
            )
        )
);

-- Products included in each sale
CREATE TABLE sale_items (
    sale_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    sale_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,

    quantity INTEGER NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    unit_cost NUMERIC(12, 2) NOT NULL,

    FOREIGN KEY (sale_id)
        REFERENCES sales(sale_id),

    FOREIGN KEY (product_id)
        REFERENCES products(product_id),

    CONSTRAINT uq_sale_product
        UNIQUE (sale_id, product_id),

    CONSTRAINT chk_sale_quantity
        CHECK (quantity > 0),

    CONSTRAINT chk_sale_unit_price
        CHECK (unit_price >= 0),

    CONSTRAINT chk_sale_unit_cost
        CHECK (unit_cost >= 0)
);

-- Purchase orders
CREATE TABLE purchase_orders (
    purchase_order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    supplier_id BIGINT NOT NULL,
    branch_id BIGINT NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'draft',

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    received_at TIMESTAMPTZ,

    FOREIGN KEY (supplier_id)
        REFERENCES suppliers(supplier_id),

    FOREIGN KEY (branch_id)
        REFERENCES branches(branch_id),

    CONSTRAINT chk_purchase_status
        CHECK (status IN ('draft', 'received')),

    CONSTRAINT chk_purchase_received
        CHECK (
            (status = 'draft' AND received_at IS NULL)
            OR
            (status = 'received' AND received_at IS NOT NULL)
        ),

    CONSTRAINT chk_purchase_dates
        CHECK (
            received_at IS NULL
            OR received_at >= created_at
        )
);

-- Products included in purchase orders
CREATE TABLE purchase_order_items (
    purchase_order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    purchase_order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,

    quantity INTEGER NOT NULL,
    unit_cost NUMERIC(12, 2) NOT NULL,

    FOREIGN KEY (purchase_order_id)
        REFERENCES purchase_orders(purchase_order_id),

    FOREIGN KEY (product_id)
        REFERENCES products(product_id),

    CONSTRAINT uq_purchase_product
        UNIQUE (purchase_order_id, product_id),

    CONSTRAINT chk_purchase_quantity
        CHECK (quantity > 0),

    CONSTRAINT chk_purchase_unit_cost
        CHECK (unit_cost >= 0)
);

-- Transfers between branches
CREATE TABLE stock_transfers (
    transfer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    from_branch_id BIGINT NOT NULL,
    to_branch_id BIGINT NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'draft',

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ,

    FOREIGN KEY (from_branch_id)
        REFERENCES branches(branch_id),

    FOREIGN KEY (to_branch_id)
        REFERENCES branches(branch_id),

    CONSTRAINT chk_different_branches
        CHECK (from_branch_id <> to_branch_id),

    CONSTRAINT chk_transfer_status
        CHECK (status IN ('draft', 'completed')),

    CONSTRAINT chk_transfer_completed
        CHECK (
            (status = 'draft' AND completed_at IS NULL)
            OR
            (status = 'completed' AND completed_at IS NOT NULL)
        ),

    CONSTRAINT chk_transfer_dates
        CHECK (
            completed_at IS NULL
            OR completed_at >= created_at
        )
);

-- Products included in each transfer
CREATE TABLE stock_transfer_items (
    transfer_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    transfer_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,

    quantity INTEGER NOT NULL,

    FOREIGN KEY (transfer_id)
        REFERENCES stock_transfers(transfer_id),

    FOREIGN KEY (product_id)
        REFERENCES products(product_id),

    CONSTRAINT uq_transfer_product
        UNIQUE (transfer_id, product_id),

    CONSTRAINT chk_transfer_quantity
        CHECK (quantity > 0)
);

-- Indexes
CREATE INDEX idx_products_category
    ON products(category_id);

CREATE INDEX idx_products_brand
    ON products(brand_id);

CREATE INDEX idx_supplier_products_product
    ON supplier_products(product_id);

CREATE INDEX idx_inventory_product
    ON inventory(product_id);

CREATE INDEX idx_sales_branch_date
    ON sales(branch_id, sold_at DESC);

CREATE INDEX idx_sales_date
    ON sales(sold_at DESC);

CREATE INDEX idx_sales_customer
    ON sales(customer_id);

CREATE INDEX idx_sale_items_product
    ON sale_items(product_id);

CREATE INDEX idx_purchase_orders_supplier
    ON purchase_orders(supplier_id);

CREATE INDEX idx_purchase_orders_branch
    ON purchase_orders(branch_id);

CREATE INDEX idx_purchase_items_product
    ON purchase_order_items(product_id);

CREATE INDEX idx_transfers_from_branch
    ON stock_transfers(from_branch_id);

CREATE INDEX idx_transfers_to_branch
    ON stock_transfers(to_branch_id);

CREATE INDEX idx_transfer_items_product
    ON stock_transfer_items(product_id);

COMMIT;
